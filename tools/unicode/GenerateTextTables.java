import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.text.Normalizer;

// Generates the Unicode tables that the text extraction needs, with the JDK that runs the oracle (PDFBox 3.0.8):
//   [presentation] PDFTextStripper.normalizeWord: Normalizer.normalize(c, NFKC).trim() for U+FB00-U+FDFF and U+FE70-U+FEFF
//   [diacritic]    TextPosition.isDiacritic: Character.getType is NON_SPACING_MARK, MODIFIER_SYMBOL or MODIFIER_LETTER
//   [nfkc]         TextPosition.combineDiacritic: Normalizer.normalize(c, NFKC).trim() for each diacritic character
// Only entries whose value differs from the character itself are written to [presentation] and [nfkc].
// Format: lines starting with # are comments; a line [name] starts a section; [presentation] and [nfkc] lines are
// "<hex code point>;<hex code points of the value, separated by spaces>", [diacritic] lines are "<first>-<last>" (hex).
public final class GenerateTextTables
{
    private static boolean isDiacritic(char c)
    {
        int type = Character.getType(c);
        return type == Character.NON_SPACING_MARK
            || type == Character.MODIFIER_SYMBOL
            || type == Character.MODIFIER_LETTER;
    }

    private static String normalized(char c)
    {
        return Normalizer.normalize(String.valueOf(c), Normalizer.Form.NFKC).trim();
    }

    private static void appendEntry(StringBuilder out, char c, String value)
    {
        out.append(String.format("%04X;", (int) c));
        for (int i = 0; i < value.length(); i++)
        {
            if (i > 0)
            {
                out.append(' ');
            }
            out.append(String.format("%04X", (int) value.charAt(i)));
        }
        out.append('\n');
    }

    public static void main(String[] args) throws IOException
    {
        if (args.length != 1)
        {
            System.err.println("usage: GenerateTextTables <output file>");
            System.exit(2);
        }
        StringBuilder out = new StringBuilder();
        out.append("# Pdf4D text tables, generated by tools/unicode/GenerateTextTables.java. Do not edit.\n");
        out.append("# java.runtime.version=").append(System.getProperty("java.runtime.version")).append('\n');
        out.append("# Unicode version of the JDK: 15.0 (Java 21)\n");

        out.append("[presentation]\n");
        for (int code = 0xFB00; code <= 0xFEFF; code++)
        {
            if (code > 0xFDFF && code < 0xFE70)
            {
                continue;
            }
            char c = (char) code;
            String value = normalized(c);
            if (!value.equals(String.valueOf(c)))
            {
                appendEntry(out, c, value);
            }
        }

        out.append("[diacritic]\n");
        int start = -1;
        for (int code = 0; code <= 0x10000; code++)
        {
            boolean inRange = code <= 0xFFFF && isDiacritic((char) code);
            if (inRange && start < 0)
            {
                start = code;
            }
            else if (!inRange && start >= 0)
            {
                out.append(String.format("%04X-%04X\n", start, code - 1));
                start = -1;
            }
        }

        out.append("[nfkc]\n");
        for (int code = 0; code <= 0xFFFF; code++)
        {
            char c = (char) code;
            if (!isDiacritic(c))
            {
                continue;
            }
            String value = normalized(c);
            if (!value.equals(String.valueOf(c)))
            {
                appendEntry(out, c, value);
            }
        }

        Path path = Paths.get(args[0]);
        Files.write(path, out.toString().getBytes(StandardCharsets.UTF_8));
    }
}
