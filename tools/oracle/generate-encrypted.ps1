# Generates the encrypted corpus variants in tests/corpus/generated/encrypted/ and their manifest rows.
#   base.pdf                           unencrypted prepared base (Producer, XMP metadata, content streams)
#   <alg>-empty.pdf / <alg>-user.pdf   alg in rc4-40 (R2), rc4-128 (R3), aes-128 (R4), aes-256 (R6);
#                                      -empty: empty user password, -user: user password "user"; owner password "owner"
#   aes-256-nometa.pdf                 AES-256, EncryptMetadata false, empty user password (XMP stays unencrypted)
#   r5-sample.pdf                      copy of an existing corpus file with /R 5, when one exists
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'oracle-lib.ps1')
. (Join-Path $PSScriptRoot '..\corpus\manifest-lib.ps1')
$java = Get-OracleJava
$cp = Get-OracleClasspath
$corpus = Join-Path $script:RepoRoot 'tests\corpus'
$dir = Join-Path $corpus 'generated\encrypted'
New-Item -ItemType Directory -Force $dir | Out-Null
Get-ChildItem $dir -Filter *.pdf | Remove-Item

function Invoke-Oracle([string[]]$OracleArgs) {
    & $java -cp $cp Pdf4DOracle @OracleArgs 2>$null
    if ($LASTEXITCODE -ne 0) { throw "Pdf4DOracle failed: $($OracleArgs -join ' ')" }
}

$gen = 'generated by tools/oracle/Pdf4DOracle.java (PDFBox 3.0.8)'
$lic = 'Apache-2.0 (generated with PDFBox)'
$rows = @()
$base = Join-Path $dir 'base.pdf'
Invoke-Oracle @('--prepare', $base)
$rows += [pscustomobject]@{ file = 'generated/encrypted/base.pdf'; source_url = $gen; license = $lic; notes = 'unencrypted base of the encrypted variants; has Info Producer, XMP Metadata stream and content streams; generated from scratch because no suitable corpus file has all three' }

$revs = @{ 'rc4-40' = 'R2'; 'rc4-128' = 'R3'; 'aes-128' = 'R4'; 'aes-256' = 'R6' }
foreach ($alg in @('rc4-40', 'rc4-128', 'aes-128', 'aes-256')) {
    foreach ($kind in @('empty', 'user')) {
        $user = if ($kind -eq 'user') { 'user' } else { '<empty>' }
        $out = Join-Path $dir "$alg-$kind.pdf"
        Invoke-Oracle @('--encrypt', $base, $out, $user, 'owner', $alg)
        $notes = "encrypted $($revs[$alg]); owner password owner"
        if ($kind -eq 'user') { $notes += '; password=user' }
        $rows += [pscustomobject]@{ file = "generated/encrypted/$alg-$kind.pdf"; source_url = $gen; license = $lic; notes = $notes }
    }
}
$nometa = Join-Path $dir 'aes-256-nometa.pdf'
Invoke-Oracle @('--encrypt', $base, $nometa, '<empty>', 'owner', 'aes-256', '--nometa')
$rows += [pscustomobject]@{ file = 'generated/encrypted/aes-256-nometa.pdf'; source_url = $gen; license = $lic; notes = 'encrypted R6, EncryptMetadata false: XMP stream is stored unencrypted; owner password owner; empty user password' }

# R5: an existing corpus file with /R 5 (deprecated Adobe extension), if the corpus has one
$r5 = $null
foreach ($f in Get-ChildItem $corpus -Recurse -File -Filter *.pdf) {
    if ($f.FullName.StartsWith($dir)) { continue }
    if ($f.Length -gt 5MB) { continue }
    $text = [Text.Encoding]::GetEncoding(28591).GetString([IO.File]::ReadAllBytes($f.FullName))
    if ($text -match '/Filter\s*/Standard' -and $text -match '/R\s+5[^0-9]') { $r5 = $f; break }
}
if ($r5) {
    Copy-Item $r5.FullName (Join-Path $dir 'r5-sample.pdf')
    $rel = $r5.FullName.Substring($corpus.Length + 1).Replace('\', '/')
    $m = Read-Manifest
    $pwNote = ''
    if ($m.Contains($rel) -and $m[$rel].notes -match '(password=\S+)') { $pwNote = ' ' + $Matches[1] }
    $rows += [pscustomobject]@{ file = 'generated/encrypted/r5-sample.pdf'; source_url = "copy of $rel"; license = 'Apache-2.0 (PDFBox test resource)'; notes = ('encrypted R5 sample' + $pwNote) }
    Write-Host "R5 sample: $rel"
} else {
    $rows += [pscustomobject]@{ file = 'generated/encrypted/r5-sample.pdf'; source_url = ''; license = ''; notes = 'MISSING: no R5 sample in the PDFBox corpus; PDFBox 3 cannot write R5' }
    Write-Warning 'No R5 sample found in the corpus.'
}
Update-ManifestPrefix 'generated/encrypted/' $rows
Write-Host ("Generated {0} files in {1}" -f (Get-ChildItem $dir -Filter *.pdf).Count, $dir)
